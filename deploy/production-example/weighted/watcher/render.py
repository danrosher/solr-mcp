"""Pure logic for the zk-watcher: parse the colour->nodes map and the weights, render nginx config.

No I/O and no ZooKeeper here, so it is unit-tested on its own (test_render.py).

The znode value is only ever a set of WEIGHTS. Node addresses come from the local colours file,
so a bad or malicious znode value cannot point the proxy at an arbitrary host.
"""
import re

COLOUR_RE = re.compile(r"^[a-z][a-z0-9_]{0,31}$")
NODE_RE = re.compile(r"^[A-Za-z0-9]([A-Za-z0-9.-]*[A-Za-z0-9])?:[0-9]{1,5}$")
MAX_WEIGHT = 1_000_000


class ConfigError(ValueError):
    """Input that must not be applied. The caller keeps the last good config."""


def parse_colours(text):
    """`blue=10.1.0.11:8983 10.1.0.12:8983` per line -> {"blue": [nodes]}. Fatal if invalid."""
    colours = {}
    for lineno, raw in enumerate(text.splitlines(), 1):
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        name, sep, rest = line.partition("=")
        name = name.strip()
        if not sep or not COLOUR_RE.match(name):
            raise ConfigError(f"colours line {lineno}: expected 'name=host:port ...', name must match {COLOUR_RE.pattern}")
        if name in colours:
            raise ConfigError(f"colours line {lineno}: duplicate colour '{name}'")
        nodes = rest.replace(",", " ").split()
        if not nodes:
            raise ConfigError(f"colours line {lineno}: '{name}' has no nodes")
        for n in nodes:
            if not NODE_RE.match(n) or not 0 < int(n.rsplit(":", 1)[1]) < 65536:
                raise ConfigError(f"colours line {lineno}: bad node '{n}' (want host:port)")
        colours[name] = nodes
    if not colours:
        raise ConfigError("colours file defines no colours")
    return colours


def parse_weights(text, colours):
    """Znode value -> {colour: int} for EVERY known colour (absent = 0).

    Entries are `colour=int`, separated by newlines or commas (so both a properties file and
    `blue=120,green=90` work). `#` starts a comment. Keys that are not known colours are ignored
    (the file may carry other settings). A known colour with a bad value rejects the whole value.
    """
    weights = {}
    for raw in text.replace(",", "\n").splitlines():
        line = raw.split("#", 1)[0].strip()
        if not line:
            continue
        key, sep, val = line.partition("=")
        key, val = key.strip(), val.strip()
        if not sep or key not in colours:
            continue
        if not re.fullmatch(r"[0-9]{1,7}", val) or int(val) > MAX_WEIGHT:
            raise ConfigError(f"weight for '{key}' must be an integer 0..{MAX_WEIGHT}, got {val!r}")
        if key in weights:
            raise ConfigError(f"weight for '{key}' appears twice")
        weights[key] = int(val)
    result = {c: weights.get(c, 0) for c in colours}
    if sum(result.values()) == 0:
        raise ConfigError("all weights are zero (or none of the known colours are present)")
    return result


def shares(weights):
    """-> (active, hundredths): `active` colours in render order, `hundredths` the percent*100 of
    every active colour except the last, which takes the remainder (`*` in split_clients)."""
    pos = sorted(c for c, w in weights.items() if w > 0)
    total = sum(weights[c] for c in pos)
    hundredths = {}
    for c in pos[:-1]:
        h = weights[c] * 10000 // total
        if h > 0:                       # below 0.01%: treated as zero
            hundredths[c] = h
    return list(hundredths) + [pos[-1]], hundredths


def render(colours, weights):
    active, hundredths = shares(weights)
    out = [
        "# GENERATED by zk-watcher. Do not edit: it is rewritten whenever the znode changes.",
        "# weights: " + ", ".join(f"{c}={weights[c]}" for c in sorted(weights)),
        "",
        "log_format solr '$time_iso8601 $status \"$request_method $uri\" cluster=$solr_cluster upstream=$upstream_addr';",
        "",
    ]
    for c in sorted(colours):
        out.append(f"upstream solr_{c} {{")
        for n in colours[c]:
            out.append(f"  server {n} max_fails=2 fail_timeout=10s;")
        if c in active:
            # Fallback only to a colour that is itself receiving traffic: weight 0 means
            # "drained / not ready" and must never be used as a backup.
            for o in sorted(active):
                if o != c:
                    for n in colours[o]:
                        out.append(f"  server {n} backup max_fails=2 fail_timeout=10s;")
        out.append(f"  zone solr_{c} 64k;")
        out.append("  keepalive 16;")
        out.append("}")
        out.append("")
    out.append("split_clients $request_id $solr_cluster {")
    for c in active[:-1]:
        h = hundredths[c]
        out.append(f"  {h // 100}.{h % 100:02d}% solr_{c};")
    out.append(f"  * solr_{active[-1]};")
    out.append("}")
    return "\n".join(out) + "\n"
